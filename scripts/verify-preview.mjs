 const completeFuture=transitData?.results?.length===2 && transitData.results.every((result)=>result.status==='available' && Date.parse(result.route?.startAt)-15*60000>Date.now());
 if(!completeFuture)assert.equal(await page.getByText('Not available',{exact:true}).count(),1,'partial or expired routes must not fabricate a deadline');
