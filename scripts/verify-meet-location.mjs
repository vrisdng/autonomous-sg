import {chromium} from 'playwright';
import {expect} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const context=await browser.newContext({viewport:{width:360,height:800},geolocation:{latitude:1.35,longitude:103.82},permissions:['geolocation']});
 const page=await context.newPage(),searches=[];
 await page.addInitScript(()=>localStorage.setItem('bojio.plan-draft.v1',JSON.stringify({code:'ABF234',participants:[{id:'me',name:'Alice',origin:'West',location:{label:'West',latitude:1.2,longitude:103.7}},{id:'friend',name:'Ben',origin:'East',location:{label:'East',latitude:1.4,longitude:103.9}}],remote:{role:'host',participantId:'me',published:false}})));
 await page.route('**/functions/v1/**',r=>{const body=r.request().postDataJSON();if(body?.action==='nearby')searches.push(body.center);return r.fulfill({json:{places:[],checkedAt:new Date().toISOString(),locations:[{label:'Typed place',latitude:1.31,longitude:103.81}],results:[]}});});
 await page.goto(process.env.BOJIO_PREVIEW_URL||'http://127.0.0.1:8082/');
 const party=page.getByRole('button',{name:'Close party options'});
 if(await party.isVisible().catch(()=>false))await party.click();
 await page.getByRole('button',{name:'Meet',exact:true}).click();
 await page.getByRole('button',{name:'Choose restaurant search area'}).click();
 const current=page.getByRole('button',{name:'Use my current location ⌖'});
 const typed=page.getByLabel('Or type a location');
 await expect(typed).toBeVisible();
 await expect(page.getByText('Search area only · no personal destination changed.')).toBeVisible();
 const placed=await page.evaluate(()=>{
  const paint=(el)=>{let node=el;while(node){const bg=getComputedStyle(node).backgroundColor;if(bg&&bg!=='transparent'&&bg!=='rgba(0, 0, 0, 0)')return bg;node=node.parentElement;}return '';};
  const currentEl=document.querySelector('[aria-label="Use my current location ⌖"]');
  const typedEl=document.querySelector('[aria-label="Or type a location"]').parentElement;
  const food=[...document.querySelectorAll('[role="button"]')].find(el=>el.textContent?.includes('Find food nearby'));
  const box=el=>{const r=el.getBoundingClientRect();return {x:r.x,y:r.y,w:r.width,h:r.height};};
  return {current:box(currentEl),typed:box(typedEl),fill:{current:paint(currentEl),typed:paint(typedEl),food:food?paint(food):''},ink:getComputedStyle(currentEl.firstElementChild).color};
 });
 assert.ok(placed.current.x+placed.current.w<=placed.typed.x+4&&Math.abs(placed.current.y-placed.typed.y)<8,'Current location and type-a-location sit side by side');
 assert.equal(placed.fill.current,placed.fill.typed);
 assert.equal(placed.fill.food,placed.fill.current);
 assert.equal(placed.fill.current,'rgb(228, 237, 188)');
 assert.notEqual(placed.ink,'rgb(255, 255, 255)');
 await current.click();
 await expect(typed).toBeHidden();
 await expect.poll(()=>searches.at(-1)?.latitude).toBe(1.35);
 assert.equal(searches.at(-1).longitude,103.82);
 const saved=await page.evaluate(()=>({draft:JSON.parse(localStorage.getItem('bojio.plan-draft.v1')),area:JSON.parse(sessionStorage.getItem('bojio.meet-area:ABF234'))}));
 assert.equal(saved.draft.participants[0].location.latitude,1.2);
 assert.equal(saved.area.label,'Current location');
 assert.equal(saved.area.latitude,1.35);
 await expect(page.getByText('Search near here')).toBeVisible();
 await page.getByRole('button',{name:'Choose restaurant search area'}).click();
 await page.getByRole('button',{name:'Meet in the middle · 2/2 locations'}).click();
 await expect.poll(()=>searches.at(-1)?.latitude).toBeCloseTo(1.3);
 assert.ok(Math.abs(searches.at(-1).longitude-103.8)<1e-8);
 await page.getByRole('button',{name:'Choose restaurant search area'}).click();
 await typed.fill('Orchard');
 await page.getByRole('button',{name:'Typed place',exact:true}).click();
 await expect(typed).toBeVisible();
 await page.getByRole('button',{name:'Find food nearby →'}).click();
 await expect.poll(()=>searches.at(-1)?.latitude).toBe(1.31);
 await expect(typed).toBeHidden();
 await page.getByRole('button',{name:'Choose restaurant search area'}).click();
 await context.clearPermissions();
 await page.evaluate(()=>Object.defineProperty(navigator,'geolocation',{value:{getCurrentPosition:(_,fail)=>fail({code:1})},configurable:true}));
 await page.getByRole('button',{name:'Use my current location ⌖'}).click();
 await expect(page.getByText('Location access was declined. Type an address below.')).toBeVisible();
 await expect(typed).toBeVisible();
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('bojio.plan-draft.v1')).participants[0].location.latitude),1.2);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 console.log('PASS side-by-side search choices, current location sets area and closes, home unchanged, typed confirm, midpoint, denial fallback, 360px width. Providers mocked; no paid calls.');
}finally{await browser.close();}
