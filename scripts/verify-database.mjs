  await db.exec('reset role; set role service_role');
  assert.equal(await rpc('select public.consume_travel_budget($1,15) as value', ['a'.repeat(64)]), false);
  assert.equal(await rpc('select public.consume_travel_budget($1,4) as value', ['global']), false);
  for (let i=0;i<11;i++) assert.equal(await rpc('select public.consume_travel_budget($1,14) as value', ['a'.repeat(64)]), true);
  assert.equal(await rpc('select public.consume_travel_budget($1,14) as value', ['a'.repeat(64)]), false);
  assert.equal(await rpc('select public.consume_travel_budget($1,14) as value', ['b'.repeat(64)]), true);
  assert.equal(await rpc('select public.consume_travel_budget($1,14) as value', ['b'.repeat(64)]), true);
  assert.equal(await rpc('select public.consume_travel_budget($1,14) as value', ['b'.repeat(64)]), false);
  console.log('PASS: weighted global/client provider budgets; public execution denied.');
